from fpdf import FPDF
import matplotlib.pyplot as plt
import io
import datetime
import numpy as np
import tempfile
import os

class PDFReport(FPDF):
    def header(self):
        # Logo placeholder or Title
        self.set_font('helvetica', 'B', 20)
        self.set_text_color(13, 17, 23)
        self.cell(0, 10, 'TENSORX CLINICAL REPORT', border=False, ln=True, align='L')
        self.set_font('helvetica', 'I', 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 5, 'AI-Powered ECG Pattern Recognition & Analysis', border=False, ln=True, align='L')
        self.ln(10)
        # Horizontal line
        self.set_draw_color(226, 232, 240)
        self.line(10, 30, 200, 30)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by TensorX AI Engine | {datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")}', align='C')

def clean_text(text):
    """Replace common unicode characters that latin-1 (default FPDF font) doesn't support."""
    if not text: return ""
    replacements = {
        "\u202f": " ", # Narrow no-break space
        "\u00a0": " ", # No-break space
        "\u2013": "-", # En dash
        "\u2014": "-", # Em dash
        "\u2018": "'", # Left single quote
        "\u2019": "'", # Right single quote
        "\u201c": '"', # Left double quote
        "\u201d": '"', # Right double quote
        "\u2022": "-", # Bullet point
    }
    for char, replacement in replacements.items():
        text = text.replace(char, replacement)
    # Fallback: remove any other non-latin-1 characters
    return text.encode("latin-1", "ignore").decode("latin-1")

def generate_pdf_report(patient_data: dict, prediction: str, probabilities: dict, vitals: dict, analysis: dict, filtered_signal: list):
    # Defensive checks
    if not patient_data: patient_data = {}
    if not vitals: vitals = {}
    if not analysis: analysis = {}
    if not probabilities: probabilities = {}

    print(f"DEBUG: Generating PDF for {patient_data.get('name', 'Unknown')}")
    pdf = PDFReport()
    pdf.add_page()
    
    # 1. Patient Information Section
    pdf.set_font('helvetica', 'B', 14)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(0, 10, 'PATIENT INFORMATION', ln=True)
    
    pdf.set_font('helvetica', '', 11)
    col_width = 95
    
    # Grid layout for patient info
    pdf.cell(col_width, 8, f"Name: {clean_text(str(patient_data.get('name', 'N/A')))}")
    pdf.cell(col_width, 8, f"Age: {clean_text(str(patient_data.get('age', 'N/A')))} Years", ln=True)
    
    pdf.cell(col_width, 8, f"Email: {clean_text(str(patient_data.get('email', 'N/A')))}")
    pdf.cell(col_width, 8, f"Blood Group: {clean_text(str(patient_data.get('blood_group', 'N/A')))}", ln=True)
    
    pdf.ln(5)
    
    # 2. Vital Signs Section
    pdf.set_font('helvetica', 'B', 14)
    pdf.cell(0, 10, 'VITAL SIGNS', ln=True)
    
    pdf.set_font('helvetica', '', 11)
    hr = vitals.get('heart_rate', '--')
    bp = f"{vitals.get('bp_sys', '--')}/{vitals.get('bp_dia', '--')}"
    spo2 = vitals.get('spo2', '--')
    
    pdf.cell(63, 8, f"Heart Rate: {hr} BPM")
    pdf.cell(63, 8, f"BP (Sys/Dia): {bp} mmHg")
    pdf.cell(63, 8, f"SpO2: {spo2}%", ln=True)
    
    pdf.ln(5)
    
    # 3. AI Diagnostic Result
    pdf.set_font('helvetica', 'B', 14)
    pdf.cell(0, 10, 'AI DIAGNOSTIC SUMMARY', ln=True)
    
    # Result Box
    pdf.set_fill_color(248, 250, 252)
    pdf.set_draw_color(226, 232, 240)
    pdf.rect(10, pdf.get_y(), 190, 25, 'FD')
    
    pdf.set_y(pdf.get_y() + 5)
    pdf.set_font('helvetica', 'B', 16)
    
    # Color based on prediction
    if prediction == "NSR":
        pdf.set_text_color(16, 185, 129) # Emerald
    elif prediction == "AFib":
        pdf.set_text_color(245, 158, 11) # Orange
    else:
        pdf.set_text_color(244, 63, 94)  # Rose
        
    pdf.cell(0, 8, f"Primary Finding: {clean_text(prediction)}", align='C', ln=True)
    
    pdf.set_font('helvetica', 'B', 10)
    pdf.set_text_color(100, 116, 139)
    probs_str = " | ".join([f"{k}: {v*100:.1f}%" for k, v in probabilities.items()])
    pdf.cell(0, 6, clean_text(probs_str), align='C', ln=True)
    
    pdf.set_text_color(0, 0, 0)
    pdf.ln(10)
    
    # 4. Clinical Interpretation (LLM)
    pdf.set_font('helvetica', 'B', 14)
    pdf.cell(0, 10, 'CLINICAL INTERPRETATION', ln=True)
    
    pdf.set_font('helvetica', '', 11)
    pdf.multi_cell(0, 6, clean_text(analysis.get('interpretation', 'No interpretation provided.')))
    
    pdf.ln(5)
    
    # 5. Recommended Actions
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, 'Immediate Clinical Steps:', ln=True)
    pdf.set_font('helvetica', '', 11)
    for step in analysis.get('quick_steps', []):
        pdf.cell(10)
        pdf.cell(0, 6, f"- {clean_text(step)}", ln=True)
    
    pdf.ln(5)

    # 6. ECG Visualization
    tmp_path = None
    try:
        if filtered_signal and len(filtered_signal) > 0:
            pdf.set_font('helvetica', 'B', 14)
            pdf.cell(0, 10, 'ECG WAVEFORM (LEAD II)', ln=True)
            
            # Create plot
            plt.figure(figsize=(10, 4))
            plt.plot(np.arange(len(filtered_signal))/250, filtered_signal, color='#2563eb', linewidth=1)
            plt.title('Filtered ECG Signal (0.5-40Hz)', fontsize=10)
            plt.xlabel('Time (s)', fontsize=8)
            plt.ylabel('Amplitude (mV)', fontsize=8)
            plt.grid(True, which='both', linestyle='--', linewidth=0.5, color='#cbd5e1')
            plt.tight_layout()
            
            # Create temp file (Windows safe)
            fd, tmp_path = tempfile.mkstemp(suffix='.png')
            os.close(fd)
            
            plt.savefig(tmp_path, format='png', dpi=150)
            plt.close()
            
            pdf.image(tmp_path, w=190)
            pdf.ln(5)
    except Exception as e:
        print(f"ERROR plotting ECG in PDF: {str(e)}")
        pdf.set_font('helvetica', 'I', 10)
        pdf.set_text_color(244, 63, 94)
        pdf.cell(0, 10, f'Error generating visualization: {str(e)}', ln=True)
    finally:
        if tmp_path and os.path.exists(tmp_path):
            try: os.remove(tmp_path)
            except: pass
        
    # Final Disclaimer - Ensure it's at the bottom or on a new page if no space
    if pdf.get_y() > 240:
        pdf.add_page()
    else:
        pdf.ln(10)

    pdf.set_font('helvetica', 'I', 8)
    pdf.set_text_color(148, 163, 184)
    pdf.set_draw_color(226, 232, 240)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(2)
    pdf.multi_cell(0, 4, "DISCLAIMER: This report is generated by an Artificial Intelligence system for screening purposes only. It must be reviewed and validated by a qualified medical professional before making any clinical decisions.", align='C')
    
    return pdf.output()
